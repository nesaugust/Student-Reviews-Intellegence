import pandas as pd
from sklearn.metrics import classification_report

# Calculate per-theme agreement with LLM pseudo-labels.
report = classification_report(
    y_test,
    baseline_predictions,
    target_names=THEMES,
    output_dict=True,
    zero_division=0
)

theme_names = {
    "teaching_clarity": "Teaching clarity",
    "learning_materials": "Learning materials",
    "assessment": "Assessment",
    "workload_pacing": "Workload & pacing",
    "feedback_support": "Feedback & support",
    "accessibility_platform": "Accessibility & platform",
    "other": "Other",
    "general_feedback": "General feedback"
}

rows = []

for index, theme in enumerate(THEMES):
    metrics = report[theme]

    rows.append({
        "theme": theme,
        "theme_label": theme_names[theme],
        "precision": float(metrics["precision"]),
        "recall": float(metrics["recall"]),
        "f1_score": float(metrics["f1-score"]),
        "train_support": int(y_train[:, index].sum()),
        "test_support": int(y_test[:, index].sum()),
        "reference_labels": "LLM-generated pseudo-labels"
    })

theme_metrics = pd.DataFrame(rows)

display(theme_metrics)

# Save actual metrics and label counts for Power BI.
(
    spark.createDataFrame(theme_metrics)
    .write
    .format("delta")
    .mode("overwrite")
    .saveAsTable(
        "workspace.feedback_gold.pseudo_label_theme_metrics"
    )
)

print("Per-theme metrics saved.")