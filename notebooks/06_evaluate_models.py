# COMMAND ----------

# Convert binary predictions back into theme names.
predicted_themes = mlb.inverse_transform(
    baseline_predictions
)

comparison = test[
    ["review_id", "course_id", "review_text", "themes"]
].copy()

comparison = comparison.rename(
    columns={"themes": "llm_reference_themes"}
)

comparison["baseline_themes"] = [
    ";".join(themes)
    for themes in predicted_themes
]

# Compare label sets regardless of their ordering.
comparison["matches_llm"] = [
    set(reference) == set(prediction)
    for reference, prediction in zip(
        test["theme_list"],
        predicted_themes
    )
]

print("Test reviews:", len(comparison))
print(
    "Reviews with different theme sets:",
    int((~comparison["matches_llm"]).sum())
)

display(
    comparison[
        ~comparison["matches_llm"]
    ].head(20)
)

